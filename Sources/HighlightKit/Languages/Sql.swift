        // turns a multi-word keyword combo into a regex that doesn't
        // care about extra whitespace etc.
        // input: "START QUERY"
        // output: /\bSTART\s+QUERY\b/
        func kwsToRegex(_ list: [String]) -> String {
            #"\b"#
                + RegexSource.either(list.map { kw in
                    guard let range = kw.range(of: #"\s+"#, options: .regularExpression) else {
                        return kw
                    }
                    return kw.replacingCharacters(in: range, with: #"\s+"#)
                })
                + #"\b"#
        }

        let multiWordKeywords = Mode(
            scope: "keyword",
            match: .re(kwsToRegex(combos)),
            relevance: 0
        )

        // keywords with less than 3 letters are reduced in relevancy
        func reduceRelevancy(_ list: [String], when qualifies: (String) -> Bool) -> [String] {
            list.map { item in
                if item.range(of: #"\|\d+$"#, options: .regularExpression) != nil {
                    return item
                } else if qualifies(item) {
                    return item + "|0"
                } else {
                    return item
                }
            }
        }

        // In highlight.js the keyword object's insertion order decides which
        // scope wins when a word appears in several groups: later groups
        // (literal, type, built_in) overwrite earlier ones (keyword). Swift
        // dictionaries are unordered, so resolve those collisions up front.
        func stripRelevance(_ item: String) -> String {
            guard let bar = item.firstIndex(of: "|") else { return item }
            return String(item[..<bar])
        }
