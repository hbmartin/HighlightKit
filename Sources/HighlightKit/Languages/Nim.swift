import Foundation

extension LanguageCatalog {
    /// Nim. Port of highlight.js `languages/nim.js`.
    public static let nim = LanguageDescriptor(name: "nim") {
        let types = [
            "int",
            "int8",
            "int16",
            "int32",
            "int64",
            "uint",
            "uint8",
            "uint16",
            "uint32",
            "uint64",
            "float",
            "float32",
            "float64",
            "bool",
            "char",
            "string",
            "cstring",
            "pointer",
            "expr",
            "stmt",
            "void",
            "auto",
            "any",
            "range",
            "array",
            "openarray",
            "varargs",
            "seq",
            "set",
            "clong",
            "culong",
            "cchar",
            "cschar",
            "cshort",
            "cint",
            "csize",
            "clonglong",
            "cfloat",
            "cdouble",
            "clongdouble",
            "cuchar",
            "cushort",
            "cuint",
            "culonglong",
            "cstringarray",
            "semistatic",
        ]
        let keywords = [
            "addr",
            "and",
            "as",
            "asm",
            "bind",
            "block",
            "break",
            "case",
            "cast",
            "concept",
            "const",
            "continue",
            "converter",
            "defer",
            "discard",
            "distinct",
            "div",
            "do",
            "elif",
            "else",
            "end",
            "enum",
            "except",
            "export",
            "finally",
            "for",
            "from",
            "func",
            "generic",
            "guarded",
            "if",
            "import",
            "in",
            "include",
            "interface",
            "is",
            "isnot",
            "iterator",
            "let",
            "macro",
            "method",
            "mixin",
            "mod",
            "nil",
            "not",
            "notin",
            "object",
            "of",
            "or",
            "out",
            "proc",
            "ptr",
            "raise",
            "ref",
            "return",
            "shared",
            "shl",
            "shr",
            "static",
            "template",
            "try",
            "tuple",
            "type",
            "using",
            "var",
            "when",
            "while",
            "with",
            "without",
            "xor",
            "yield",
        ]
        let builtIns = [
            "stdin",
            "stdout",
            "stderr",
            "result",
        ]
        let literals = [
            "true",
            "false",
        ]
        return LanguageDefinition(
            name: "nim",
            root: Mode(
                keywords: Keywords([
                    "keyword": Keywords.Group(words: keywords),
                    "literal": Keywords.Group(words: literals),
                    "type": Keywords.Group(words: types),
                    "built_in": Keywords.Group(words: builtIns),
                ]),
                contains: [
                    Mode(
                        scope: "meta", // Actually pragma
                        begin: #"\{\."#,
                        end: #"\.\}"#,
                        relevance: 10
                    ),
                    Mode(
                        scope: "string",
                        begin: #"[a-zA-Z]\w*""#,
                        end: "\"",
                        contains: [Mode(begin: "\"\"")]
                    ),
                    Mode(
                        scope: "string",
                        begin: #"([a-zA-Z]\w*)?""""#,
                        end: "\"\"\""
                    ),
                    CommonModes.quoteStringMode,
                    Mode(
                        scope: "type",
                        begin: #"\b[A-Z]\w+\b"#,
                        relevance: 0
                    ),
                    Mode(
                        scope: "number",
                        variants: [
                            Mode(begin: #"\b(0[xX][0-9a-fA-F][_0-9a-fA-F]*)('?[iIuU](8|16|32|64))?"#),
                            Mode(begin: #"\b(0o[0-7][_0-7]*)('?[iIuUfF](8|16|32|64))?"#),
                            Mode(begin: #"\b(0(b|B)[01][_01]*)('?[iIuUfF](8|16|32|64))?"#),
                            Mode(begin: #"\b(\d[_\d]*)('?[iIuUfF](8|16|32|64))?"#),
                        ],
                        relevance: 0
                    ),
                    CommonModes.hashCommentMode,
                ]
            )
        )
    }
}
