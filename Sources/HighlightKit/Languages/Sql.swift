        let keywordWords = reduceRelevancy(keywords, when: { $0.count < 3 }).filter { item in
            let word = stripRelevance(item)
            return !literalSet.contains(word) && !typeSet.contains(word) && !builtInSet.contains(word)
        }
        let literalWords = literals.filter { !typeSet.contains($0) && !builtInSet.contains($0) }
        let typeWords = types.filter { !builtInSet.contains($0) }

